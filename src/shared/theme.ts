/**
 * 外壳硬编码色的唯一来源（主进程侧）。
 *
 * 渲染层的颜色真相源是 `renderer/src/assets/theme.css` 里的 `--c-*`，
 * 但其中三个值**主进程也必须知道**：`BrowserWindow` 的 `backgroundColor`
 * 只收一个字面量，它决定窗口在页面首帧绘制出来之前那几百毫秒是什么颜色。
 *
 * 早先这里是 `#0b1220`（slate 蓝）。换成黑金之后，那个值会在启动瞬间闪一道蓝光——
 * 转瞬即逝，只有眼睛能发现，测试永远抓不到，所以值得为它留一份共享常量。
 *
 * 代价是这 3 个 hex 在 CSS 与 TS 里各存一份。收益是不必为一个值引入
 * CSS ↔ TS 的 codegen——个人自用工具上这笔账划算。`theme.css` 顶部有反向注释
 * 指向这里，改动时两处一起改。
 */
export const SHELL = {
  bgDeep: '#060504',
  bg: '#0D0B08',
  gold: '#C9A227'
} as const

